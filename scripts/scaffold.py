"""Generates a minimal extension against today's public boundaries -- a new
environment or a new algorithm (a named actor/critic combination on the
existing `MaxEntRLPolicy` template, exactly how SAC/AMDP/DIME/SDAC are each
just a `config/models/*.yaml` entry -- see `policies/rl.py`'s docstring) --
and immediately smoke-tests the generated output in a temporary project
before declaring success. Refuses to overwrite an existing file.

    uv run python scripts/scaffold.py env TinyPendulum --gym-id Pendulum-v1
    uv run python scripts/scaffold.py algorithm MyAlgo --actor StochasticActor --critic C51Critic

An environment scaffold needs no central registry edit: it is selected
purely through the external `module:Class` path
(`env: "<generated_module>:<ClassName>"`), the same mechanism
`examples/cpu_quickstart.py` demonstrates. An algorithm scaffold generates a
`config/models/<name>.yaml`-shaped file; drop it into your own config root
(`BARL_CONFIG_DIR`, or pass `--config-root` to `ConfigTree`) to use it for
real -- this script only proves it resolves and satisfies the Policy
contract, in a disposable copy of the packaged defaults.
"""

import argparse
import importlib.util
import os
import shutil
import tempfile
from pathlib import Path

os.environ.setdefault("JAX_PLATFORMS", "cpu")
os.environ.setdefault("MUJOCO_GL", "egl")

ENV_TEMPLATE = '''"""Generated by scripts/scaffold.py env -- a lazy, importable Environment
factory. Select it without editing any central registry:

    env: "{module_hint}:{class_name}"

Fill in `stats` with this environment's real achievable per-episode return
(a categorical critic's fixed support needs it) and swap `get_env()`'s
`gym.make(...)` for a real construction. Import simulator dependencies
inside `get_env()`, not at module level (see CLAUDE.md)."""

import gymnasium as gym

from barl_jax.env import Environment


class {class_name}(Environment):
  stats = {{"return_min": -1000.0, "return_max": 1000.0}}  # TODO: real bounds

  def get_env(self) -> gym.Env:
    return gym.make("{gym_id}")

  def get_dataset(self):
    raise NotImplementedError("{class_name} has no offline dataset.")
'''

MODEL_TEMPLATE = """{name}:
  policy: MaxEntRLPolicy
  training:
    batch_size: 256
    utd_ratio: 2.0

  params:
    entropy_scale: -1.0
    policy_delay: 1
    normalize_obs: true
    entropy_in_target: true

  components:
    actor:   {{class: {actor}, tier: medium}}
    critic:  {{class: {critic}, tier: medium}}
    entropy: {{class: AutotuneRegulator}}
"""


def _write_new_file(path: Path, content: str) -> None:
  if path.exists():
    raise SystemExit(f"{path} already exists -- scaffold refuses to overwrite it. "
                     f"Remove it or pass a different name/--out.")
  path.parent.mkdir(parents=True, exist_ok=True)
  path.write_text(content)
  print(f"wrote {path}")


def _load_module(path: Path, name: str):
  spec = importlib.util.spec_from_file_location(name, path)
  module = importlib.util.module_from_spec(spec)
  spec.loader.exec_module(module)
  return module


def scaffold_env(class_name: str, gym_id: str, out: Path) -> None:
  path = out / f"{class_name.lower()}_env.py"
  module_hint = f"{out.name}.{path.stem}" if out != Path(".") else path.stem
  _write_new_file(path, ENV_TEMPLATE.format(class_name=class_name, gym_id=gym_id,
                                            module_hint=module_hint))
  _smoke_test_env(path, class_name, gym_id)


def _smoke_test_env(path: Path, class_name: str, gym_id: str) -> None:
  """Imports the generated module from a temp copy (proving it stands alone,
  not just next to files that happen to be on sys.path already), builds the
  class, and exercises get_env/get_env_stats/reset/step/close once."""
  with tempfile.TemporaryDirectory() as tmp:
    copy = Path(tmp) / path.name
    shutil.copy(path, copy)
    module = _load_module(copy, f"_scaffold_smoke_{class_name}")
    cls = getattr(module, class_name)
    instance = cls()
    env = instance.get_env()
    try:
      stats = instance.get_env_stats(env)
      assert stats["obs_dim"] > 0, "obs_dim must be positive"
      obs, _ = env.reset(seed=0)
      env.step(env.action_space.sample())
    finally:
      env.close()
  print(f"smoke test OK: {class_name} ({gym_id}) builds, resets and steps.")


def scaffold_algorithm(name: str, actor: str, critic: str, out: Path) -> None:
  path = out / f"{name.lower()}.yaml"
  _write_new_file(path, MODEL_TEMPLATE.format(name=name, actor=actor, critic=critic))
  _smoke_test_algorithm(name, path)


def _smoke_test_algorithm(name: str, model_path: Path) -> None:
  """Copies the packaged defaults into a temp config root, drops the
  generated model file into its models/ directory, and runs the same
  contract test tests/test_policies.py runs over every real model: a
  train_step whose losses match create_optimizer()'s keys and are finite,
  and an inference_step of the right shape."""
  import gymnasium as gym
  import jax.numpy as jnp
  import numpy as np

  import barl_jax  # noqa: F401 -- populates the policy/component registries
  from barl_jax.config.toolkit import CONFIG_DIR
  from barl_jax.config.tree import ConfigTree, validate
  from barl_jax.env import EnvStats
  from barl_jax.policy import Policy

  with tempfile.TemporaryDirectory() as tmp:
    root = Path(tmp) / "config"
    shutil.copytree(CONFIG_DIR, root)
    shutil.copy(model_path, root / "models" / model_path.name)

    tree = ConfigTree(root=root)
    problems = validate(name, tree)
    if problems:
      raise SystemExit(f"{name}: generated model fails validation:\n  " + "\n  ".join(problems))

    obs_dim, act_dim, batch = 5, 3, 4

    class FakeEnv:
      observation_space = gym.spaces.Box(-np.inf, np.inf, (obs_dim,), np.float32)
      action_space = gym.spaces.Box(-1.0, 1.0, (act_dim,), np.float32)

    stats = EnvStats(obs_shape=(obs_dim,), obs_dim=obs_dim, act_discrete=False, act_dim=act_dim,
                     act_low=np.full(act_dim, -1.0, np.float32), act_high=np.full(act_dim, 1.0, np.float32),
                     max_episode_steps=16, return_min=-10.0, return_max=10.0)
    policy = Policy.make(name, FakeEnv(), env_stats=stats, seed=0, config=tree)

    rng = np.random.default_rng(0)
    f = lambda *s: jnp.asarray(rng.normal(size=s), jnp.float32)
    fake_batch = {"obs": f(batch, obs_dim), "next_obs": f(batch, obs_dim),
                 "act": jnp.clip(f(batch, act_dim), -1, 1),
                 "chunk_return": f(batch), "term": jnp.zeros((batch,), jnp.float32),
                 "horizon": jnp.ones((batch,), jnp.int32)}
    losses = policy.train_step(fake_batch)
    expected = set(policy.create_optimizer())
    if set(losses) != expected:
      raise SystemExit(f"{name}: train_step losses {sorted(losses)} != "
                       f"create_optimizer() keys {sorted(expected)}")
    if not all(bool(jnp.isfinite(v)) for v in losses.values()):
      raise SystemExit(f"{name}: train_step produced a non-finite loss: {losses}")

    action, _ = policy.inference_step(f(1, obs_dim), key=__import__("jax").random.PRNGKey(0))
    if action.shape != (1, policy.chunk_size, act_dim):
      raise SystemExit(f"{name}: inference_step shape {action.shape} != "
                       f"(1, {policy.chunk_size}, {act_dim})")

  print(f"smoke test OK: {name} builds, train_step losses match create_optimizer() "
        f"and are finite, inference_step shape is right.")


if __name__ == "__main__":
  args = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
  sub = args.add_subparsers(dest="kind", required=True)

  env_p = sub.add_parser("env", help="Scaffold a new Environment subclass")
  env_p.add_argument("class_name")
  env_p.add_argument("--gym-id", required=True,
                     help="A gymnasium env id to wrap, e.g. Pendulum-v1 (swap for a real "
                          "construction once generated -- see the file's own TODOs)")
  env_p.add_argument("--out", type=Path, default=Path("."))

  algo_p = sub.add_parser("algorithm", help="Scaffold a new algorithm (model YAML)")
  algo_p.add_argument("name")
  algo_p.add_argument("--actor", required=True, help="A registered Actor class name")
  algo_p.add_argument("--critic", required=True, help="A registered Critic class name")
  algo_p.add_argument("--out", type=Path, default=Path("."))

  kwargs = args.parse_args()
  if kwargs.kind == "env":
    scaffold_env(kwargs.class_name, kwargs.gym_id, kwargs.out)
  else:
    scaffold_algorithm(kwargs.name, kwargs.actor, kwargs.critic, kwargs.out)
